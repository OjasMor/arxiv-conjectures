"""Independent check of a transitive permutation group with no derangement of prime or prime-squared order.

Group: G = V x| <A>, V = (Z/N)^2, N = 2592 = 2^5 * 3^4, A = [[0,1],[1,1]], acting on the set Omega of cosets
v + U_j, where U = <(72,0)> (cyclic of order 36) and U_j = A^j U. An element g(x) = A^k x + v sends the coset
x + U_j to (A^k x + v) + A^k U_j.

Checked here, over the whole of V with no use of the Chinese remainder theorem:
 1. A has order 432 mod N; there are exactly 12 distinct subgroups U_j; U_0 and U_1 meet only in 0.
 2. So Omega has 12 * N^2 / 36 = 2,239,488 points, G is transitive on it (translations move cosets of one
    direction, A cycles the directions), and the action is faithful.
 3. |G| = N^2 * 432 = 2,902,376,448 is a {2,3}-group, so elements of prime or prime-squared order have g^4 = 1 or g^9 = 1.
 4. EVERY g with g^4 = 1 or g^9 = 1 fixes some coset (so it is not a derangement).
 5. A^54 has order 8 and fixes no coset, so derangements exist.
"""
import numpy as np
N = 2592

def mat_mul(X, Y): return [[(X[0][0]*Y[0][0] + X[0][1]*Y[1][0]) % N, (X[0][0]*Y[0][1] + X[0][1]*Y[1][1]) % N],
                           [(X[1][0]*Y[0][0] + X[1][1]*Y[1][0]) % N, (X[1][0]*Y[0][1] + X[1][1]*Y[1][1]) % N]]
I2 = [[1, 0], [0, 1]]; A = [[0, 1], [1, 1]]
powers = [I2]
while True:
    nxt = mat_mul(powers[-1], A)
    if nxt == I2: break
    powers.append(nxt)
ordA = len(powers); assert ordA == 432, ordA

def subgroup(gen):                       # cyclic subgroup generated by a vector, as a frozenset
    return frozenset(((i * gen[0]) % N, (i * gen[1]) % N) for i in range(N))
def apply(M, v): return ((M[0][0]*v[0] + M[0][1]*v[1]) % N, (M[1][0]*v[0] + M[1][1]*v[1]) % N)

U = [subgroup(apply(powers[j], (72, 0))) for j in range(ordA)]
distinct = []
for S in U:
    if S not in distinct: distinct.append(S)
assert len(distinct) == 12 and all(len(S) == 36 for S in distinct)
assert all(U[j] == U[j % 12] for j in range(ordA))          # the directions repeat with period 12
assert U[0] & U[1] == {(0, 0)}
degree = 12 * N * N // 36
print("order of A:", ordA, " directions:", len(distinct), " degree:", degree, " |G| =", N * N * ordA)
g_order = N * N * ordA
m = g_order
for p in (2, 3):
    while m % p == 0: m //= p
assert m == 1, "group order has another prime factor"

xs, ys = np.meshgrid(np.arange(N, dtype=np.int64), np.arange(N, dtype=np.int64), indexing="ij")   # v = (xs, ys)

def mask_of(points):
    M = np.zeros((N, N), dtype=bool)
    P = np.array(list(points), dtype=np.int64); M[P[:, 0], P[:, 1]] = True
    return M

total_checked = 0
for h in (4, 9):
    for k in range(ordA):
        Mk = powers[k]
        # g(x) = A^k x + v has g^h = 1  iff  A^(kh) = I and (I + A^k + ... + A^((h-1)k)) v = 0
        if powers[(k * h) % ordA] != I2: continue
        S = [[0, 0], [0, 0]]
        for i in range(h):
            P = powers[(k * i) % ordA]; S = [[(S[a][b] + P[a][b]) % N for b in range(2)] for a in range(2)]
        ker = ((S[0][0] * xs + S[0][1] * ys) % N == 0) & ((S[1][0] * xs + S[1][1] * ys) % N == 0)
        # g fixes the coset x + U_j  iff  A^k U_j = U_j and v lies in U_j + (A^k - I) V
        B = [[(Mk[0][0] - 1) % N, Mk[0][1]], [Mk[1][0], (Mk[1][1] - 1) % N]]
        image = mask_of({((B[0][0]*a + B[0][1]*b) % N, (B[1][0]*a + B[1][1]*b) % N) for a in range(N) for b in range(N)}) if k else mask_of({(0, 0)})
        fixes = np.zeros((N, N), dtype=bool)
        im_pts = np.argwhere(image)
        for j in range(12):
            if frozenset(apply(Mk, u) for u in distinct[j]) != distinct[j]: continue
            for u in distinct[j]:
                fixes[(im_pts[:, 0] + u[0]) % N, (im_pts[:, 1] + u[1]) % N] = True
        bad = ker & ~fixes
        total_checked += int(ker.sum())
        assert not bad.any(), (h, k, np.argwhere(bad)[:3])
        print(f"h={h} k={k}: {int(ker.sum())} elements with g^{h}=1, all fix a coset")
print("elements with g^4 = 1 or g^9 = 1 checked:", total_checked, "- none is a derangement")

# a derangement: A^54 (order 8) moves every direction
M54 = powers[54]; o = 1; P = M54
while P != I2: P = mat_mul(P, M54); o += 1
assert o == 8 and all(frozenset(apply(M54, u) for u in distinct[j]) != distinct[j] for j in range(12))
print("A^54 has order 8 and fixes no coset: derangements exist")
